/**
 * Public-build site links.
 *
 * Pricing, referrals and accounts are part of the hosted site, not of this
 * repository, so those routes are absent here rather than broken. Pointing them
 * at ui.beste.co keeps every header, footer and docs page that references them
 * identical to the private build's, and sends the reader somewhere real.
 */

export const HOSTED_SITE = "https://ui.beste.co";

/**
 * Always the hosted registry, never this deployment.
 *
 * The private build derives this from an environment variable and falls back
 * to a dev server. Here there is no such variable, so the fallback would win
 * and every install command, canonical and JSON-LD URL on a public clone would
 * point at a port nobody is running.
 */
export const SITE_ORIGIN = HOSTED_SITE;

/**
 * Radix, because that is what this repository contains. The Base UI variant is
 * generated by a codemod that is not part of the public build, so offering it
 * as the default would hand out a command for sources that are not here.
 * ui.beste.co serves both, and its own default stays "base".
 */
export const DEFAULT_FLAVOR: "base" | "radix" = "radix";

/**
 * One flavor, because this repository holds one set of sources. The Base UI
 * variant is produced by a codemod that is not part of the public build, so
 * with a single option the picker hides itself rather than offering a choice
 * that resolves to nothing. ui.beste.co serves both.
 */
export const FLAVOR_OPTIONS: readonly ("base" | "radix")[] = ["radix"];

