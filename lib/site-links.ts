/**
 * Everything the hosted site serves and this build does not. A reader who
 * follows an old link, a search result or a bookmark to one of these should be
 * pointed at the real page rather than shown a dead end.
 */
export const HOSTED_ONLY_PATHS: readonly string[] = [
  "/pricing",
  "/referrals",
  "/account",
  "/favorites",
  "/docs",
  "/changelog",
  "/blog",
  // The free tools are a hosted traffic surface, not part of the library.
  "/tools",
  // The pages tier composes Pro blocks, so it is hosted-only in full: the
  // listing, the detail route and the embed all live on ui.beste.co.
  "/pages",
  "/page",
  // Most of the catalogue is Pro, so a block detail page that is missing here
  // is almost always one that exists on the hosted site rather than a typo.
  // Pieces and components are all present, so a miss there is a real 404.
  "/block",
];

