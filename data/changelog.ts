// Versions live entirely inside the 1.x.x range. Newest entry is pinned to
// v1.6.8 and we step the patch down for every older entry, rolling minor
// when patch hits 0. We never cross into v2 — the floor is v1.0.0.
// An entry can override with an explicit `version` in input.
function assignVersions(entries: ChangelogEntryInput[]): string[] {
  const versions = new Array<string>(entries.length);
  const major = 1;
  let minor = 6;
  let patch = 8;
  for (let i = 0; i < entries.length; i++) {
    const entry = entries[i];
    if (entry?.version) {
      versions[i] = entry.version;
      continue;
    }
    versions[i] = `v${major}.${minor}.${patch}`;
    if (patch > 0) {
      patch -= 1;
    } else if (minor > 0) {
      minor -= 1;
      patch = 9;
    } else {
      // Floor: stay at v1.0.0 if we somehow run out of room.
      patch = 0;
    }
  }
  return versions;
}

// Enrich changelog entries with block and piece metadata from registry
function enrichChangelog(entries: ChangelogEntryInput[]): ChangelogEntry[] {
  const versions = assignVersions(entries);
  return entries.map((entry, index) => {
    const enrichedBlocks: ChangelogBlock[] = [];
    for (const blockInput of entry.blocks ?? []) {
      const block = getBlock(blockInput.name);
      if (!block) {
        console.warn(`Block not found: ${blockInput.name}`);
        continue;
      }
      enrichedBlocks.push({
        name: block.name,
        title: block.title,
        description: block.description,
        category: block.category,
        isPro: block.isPro,
        isNew: blockInput.isNew,
        isUpdated: blockInput.isUpdated,
      });
    }
    const enrichedPieces: ChangelogPiece[] = [];
    for (const pieceInput of entry.pieces ?? []) {
      const piece = getComponent(pieceInput.name);
      if (!piece) {
        console.warn(`Piece not found: ${pieceInput.name}`);
        continue;
      }
      enrichedPieces.push({
        name: piece.name,
        title: piece.title,
        description: piece.description,
        category: piece.category,
        isPro: piece.isPro,
        isNew: pieceInput.isNew,
        isUpdated: pieceInput.isUpdated,
      });
    }
    const enrichedComponents: ChangelogComponent[] = [];
    for (const componentInput of entry.components ?? []) {
      const component = getRegistryComponent(componentInput.name);
      if (!component) {
        console.warn(`Component not found: ${componentInput.name}`);
        continue;
      }
      enrichedComponents.push({
        name: component.name,
        title: component.title,
        description: component.description,
        category: component.category,
        // Components are never Pro — never show a Pro badge for them.
        isPro: false,
        isNew: componentInput.isNew,
        isUpdated: componentInput.isUpdated,
      });
    }
    return {
      version: versions[index] ?? "v0.0.0",
      date: entry.date,
      title: entry.title,
      description: entry.description,
      blocks: enrichedBlocks,
      pieces: enrichedPieces,
      components: enrichedComponents,
      isCategoryLaunch: entry.isCategoryLaunch,
      categoryCount: entry.categoryCount,
      categoryName: entry.categoryName,
      isFeatureLaunch: entry.isFeatureLaunch,
      featureLink: entry.featureLink,
      featureEyebrow: entry.featureEyebrow,
      featureSubtitle: entry.featureSubtitle,
      tweetUrl: entry.tweetUrl,
    };
  });
}

export const changelog: ChangelogEntry[] = enrichChangelog(_changelog);
